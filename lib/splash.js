  /** 球面插值（大圆 + 拱起）：返回经纬度（度） */
  function arcPoint(A, B, t) {
    var p1 = toVec(A), p2 = toVec(B)
    var dot = Math.max(-1, Math.min(1, p1.x * p2.x + p1.y * p2.y + p1.z * p2.z))
    var omega = Math.acos(dot)
    var s = Math.sin(omega) || 1e-6
    var k1 = Math.sin((1 - t) * omega) / s
    var k2 = Math.sin(t * omega) / s
    var lift = 1 + 0.14 * Math.sin(Math.PI * t)
    var x = (p1.x * k1 + p2.x * k2) * lift
    var y = (p1.y * k1 + p2.y * k2) * lift
    var z = (p1.z * k1 + p2.z * k2) * lift
    return {
      lat: Math.asin(Math.max(-1, Math.min(1, y))) / DEG,
      lon: Math.atan2(x, z) / DEG,
      r: lift
    }
  }
  function toVec(H) {
    var phi = H[1] * DEG, lam = H[2] * DEG
    return { x: Math.cos(phi) * Math.sin(lam), y: Math.sin(phi), z: Math.cos(phi) * Math.cos(lam) }
  }

  /** 单位球面向量插值 */
  function slerpUnit(a, b, t) {
    var d = Math.max(-1, Math.min(1, a.x * b.x + a.y * b.y + a.z * b.z))
    var om = Math.acos(d)
    if (om < 1e-4) return [a.x, a.y, a.z]
    var s = Math.sin(om)
    var k1 = Math.sin((1 - t) * om) / s, k2 = Math.sin(t * om) / s
    return [a.x * k1 + b.x * k2, a.y * k1 + b.y * k2, a.z * k1 + b.z * k2]
  }
  /** 经中继点的平滑大弧：球面二次贝塞尔（slerp-of-slerp，全程贴球面，
      中继点为控制点），再叠加正弦抬升 —— 平滑过洋、无折角、绝不穿球。 */
  function arcViaPoint(A, W, B, t) {
    var a = toVec(A), b = toVec(B), w = toVec(W)
    var p1 = slerpUnit(a, w, t)
    var p2 = slerpUnit(w, b, t)
    var q = slerpUnit(p1, p2, t)
    var l = Math.sqrt(q[0] * q[0] + q[1] * q[1] + q[2] * q[2]) || 1
    return {
      lat: Math.asin(Math.max(-1, Math.min(1, q[1] / l))) / DEG,
      lon: Math.atan2(q[0], q[2]) / DEG,
      r: 1 + 0.15 * Math.sin(Math.PI * t)
    }
  }

  /** 抬升点可见性：方向分量 + 离地半径。投影在球轮廓之外必可见；
      在轮廓内则要「离地高度越过球面」才可见——修掉临边处弧线压球/穿模。 */
  function dirVisible(p, r) {
    if (p.z <= 0) return false
    var rr = p.x * p.x + p.y * p.y
    if (rr >= 1) return true
    return p.z * (r || 1) >= Math.sqrt(1 - rr)
  }

  /* 弧线连续深度淡出（零分配版）：
     可见性 = 方向 z>0（抬升弧线半径≥1，正面必不被球遮挡）；深度前向度
     f = clamp01(z/0.22) 连续映射到 alpha(0.32→1) 与线宽(0.55→1)。
     深前段整体批量描（干线带辉光），地平过渡区逐段连续渐变，一端没入
     地平的段取中点细分 —— 无离散档位跳变、无丢段缺口、无每帧对象分配
     （复用模块级暂存数组，杜绝 GC 抖动引起的闪烁）。 */
  var AX = [], AY = [], AZ = [], AT = []
  var MX = 0, MY = 0, MZ = 0
  function drawArc(c, cam, cx, cy, R, A, B, tMax, P, alpha, width, lite, via, noFade) {
    var steps = lite ? Math.max(10, Math.floor(18 * tMax)) : Math.max(12, Math.floor(28 * tMax))
    if (steps < 2) return
    var n = 0
    for (var s = 0; s <= steps; s++) {
      var t = (s / steps) * tMax
      var g = via ? arcViaPoint(A, via, B, t) : arcPoint(A, B, t)
      var p = cam(g.lat * DEG, g.lon * DEG)
      AX[n] = cx + R * p.x
      AY[n] = cy - R * p.y
      AZ[n] = p.z
      AT[n] = t
      n++
    }
    function fAt(i) { return AZ[i] > 0 ? (noFade ? 1 : clamp01(AZ[i] / 0.22)) : -1 }
    function midOf(i) {
      var g = via ? arcViaPoint(A, via, B, (AT[i] + AT[i + 1]) / 2) : arcPoint(A, B, (AT[i] + AT[i + 1]) / 2)
      var p = cam(g.lat * DEG, g.lon * DEG)
      MX = cx + R * p.x; MY = cy - R * p.y; MZ = p.z
    }
    c.save()
    c.strokeStyle = P.red
    c.lineCap = 'round'
    c.globalAlpha = alpha
    c.lineWidth = width || 1.25
    /* 深前段（两端 f>0.8）批量芯线（+辉光） */
    c.beginPath()
    for (var i = 0; i + 1 < n; i++) {
      if (fAt(i) > 0.8 && fAt(i + 1) > 0.8) {
        c.moveTo(AX[i], AY[i])
        c.lineTo(AX[i + 1], AY[i + 1])
      }
    }
    if (!lite) {
      c.globalAlpha = alpha * 0.16
      c.lineWidth = (width || 1.25) * 2.8
      c.stroke()
      c.globalAlpha = alpha
      c.lineWidth = width || 1.25
    }
    c.stroke()
    /* 过渡区：逐段连续渐变（含一端没入地平的段：画到中点） */
    for (var j = 0; j + 1 < n; j++) {
      var fa = fAt(j), fb = fAt(j + 1)
      var x1, y1, x2, y2, f
      if (fa < 0 && fb < 0) continue
      if (fa < 0 || fb < 0) {
        midOf(j)
        if (MZ <= 0) continue
        var vis = fa >= 0 ? j : j + 1
        x1 = AX[vis]; y1 = AY[vis]; x2 = MX; y2 = MY
        f = noFade ? 1 : Math.max(0.06, (fa >= 0 ? fa : fb) * 0.5)
      } else {
        x1 = AX[j]; y1 = AY[j]; x2 = AX[j + 1]; y2 = AY[j + 1]
        f = (fa + fb) / 2
      }
      if (f > 0.8) continue                     /* 已由批量芯线覆盖 */
      c.globalAlpha = alpha * (0.32 + 0.68 * f)
      c.lineWidth = (width || 1.25) * (0.55 + 0.45 * f)
      c.beginPath()
      c.moveTo(x1, y1)
      c.lineTo(x2, y2)
      c.stroke()
    }
    c.restore()
  }

  /* ── ORIGIN 开场：印尼起笔 → 拉远 → 定影上海 ───────────────────────────
     u 为阶段进度 0..1：前段雅加达近景，中段镜头拉远 + 航线按扩张史点亮，
     末段定影上海总部（汇聚弧 + 双环脉冲 + 标牌）。
     warpOrigin 做内部节奏重映射：雅加达近景与上海定影段提速，
     「拉镜头到全球」的主段保持原始速度不被压缩。 */
  function warpOrigin(u) {
    /* 450ms 近景 + 4680ms 拉远（严格原速）+ 1620ms 定影，共 6750ms */
    if (u <= 0.0667) return u / 0.0667 * 0.16
    if (u <= 0.76) return 0.16 + (u - 0.0667) / 0.6933 * 0.52
    return 0.68 + (u - 0.76) / 0.24 * 0.32
  }
  function drawOrigin(c, uRaw, t, P) {
    var u = warpOrigin(clamp01(uRaw))
    var minWH = Math.min(viewW, viewH)
    var Rf = minWH * 0.36
    /* 镜头：先按住雅加达（带一点向东的微漂移），再一路拉远，
       同时中心滑向上海。三次分段全部用五次缓动（quintic smoothstep），
       起步与落幅都带呼吸感。 */
    var pull = quintic((u - 0.16) / 0.52)
    var settle = quintic((u - 0.7) / 0.3)
    var zoom = 2.4 - 1.4 * pull
    var R = Rf * zoom
    var camLat = lerp(lerp(CGK_LAT - 4, 20, pull), SHA_LAT, settle)
    var camLon = lerp(lerp(CGK_LON + 2, 112, pull), SHA_LON, settle)
    camLon += scene.drag * 0.3 + (1 - pull) * Math.min(u * 8, 1) * 1.6
    var cx = viewW / 2, cy = viewH * 0.56
    var cam = makeCam(camLat, camLon)
    var camV = makeVecCam(camLat, camLon)
    /* 大陆显影：开局即露出南半球与印尼（起点必须可见），随镜头拉远补全到全球 */
    drawLandSphere(c, camV, cx, cy, R, P, false, lerp(0.52, 1, smooth(u * 1.2)))
    /* 近景经纬网：只在镜头贴近时淡淡出现（给近景以结构感），拉远后隐去 */
    var grat = clamp01((zoom - 1.12) / 1.1) * 0.12
    if (grat > 0.004) drawGraticule(c, cam, cx, cy, R, P, grat)

    /* 航线叙事：从雅加达铺完东南亚，最后一条线抵达上海；
       随后以与雅加达段完全相同的节奏（同跨 0.40、同缓动）从上海延伸向中东与拉美 */
    /* 全网级联开花：一条进度轴驱动整张 NET 表（六洲同时生长，无等待） */
    var prog = smooth(clamp01((u - 0.15) / 0.72)) * TOTAL_UNITS
    for (var e = 0; e < NET.length; e++) {
      var tMax = clamp01(prog - NET[e][2])
      if (tMax <= 0.01) continue
      var A = HUBS[NET[e][0]], B = HUBS[NET[e][1]]
      var kind = NET[e][3]
      if (kind === 3) {
        drawArc(c, cam, cx, cy, R, A, B, tMax, P, 0.13, 0.6, true)
        continue
      }
      if (kind === 2) {
        drawArc(c, cam, cx, cy, R, A, B, tMax, P, 0.3, 0.9, true)
        continue
      }
      if (kind === 5) {
        /* 跨太平洋平滑大弧：不做深度淡出，可见段全程满强度（级联途中也清晰） */
        drawArc(c, cam, cx, cy, R, A, B, tMax, P, 0.9, 2.8, false, HUBS[NET[e][4]], true)
        continue
      }
      var fromHQ = NET[e][0] === HQ
      var cross = NET[e][3] === 1
      var t = B[3]
      var alpha = cross ? 0.2 : fromHQ ? (t <= 1 ? 0.8 : t === 2 ? 0.5 : 0.32)
                                      : (t <= 1 ? 0.55 : t === 2 ? 0.34 : 0.2)
      var width = cross ? 0.7 : fromHQ ? (t <= 1 ? 1.4 : t === 2 ? 1.0 : 0.8)
                                      : (t <= 1 ? 1.1 : t === 2 ? 0.9 : 0.7)
      drawArc(c, cam, cx, cy, R, A, B, tMax, P, alpha, width)
    }
    /* 抵达上海：总部上电（双环脉冲 + 标牌） */
    var conv = smooth(clamp01(prog - (HUB_UNIT[HQ] + 0.5)))
    /* 枢纽点 */
    c.textAlign = 'center'
    c.textBaseline = 'middle'
    for (var h = 0; h < HUBS.length; h++) {
      if (HUBS[h][3] === 9) continue
      var hp = projHub(HUBS[h], cam, cx, cy, R)
      if (hp.z <= 0) continue
      var lit = h === 0 || prog >= HUB_LIT_AT[h] - 0.45
      /* 首次点亮：600ms 的弹跳涟漪（电影里节点上电的那一下） */
      if (lit && !hubLitAt[h]) hubLitAt[h] = performance.now()
      var popAge = hubLitAt[h] ? (performance.now() - hubLitAt[h]) / 600 : 2
      if (h === 0) {
        /* 雅加达 · 起点：持续脉冲，标签前半程可见 */
        c.fillStyle = P.red
        c.beginPath(); c.arc(hp.x, hp.y, 3.4, 0, TAU); c.fill()
        var ph = (t * 0.9) % 1
        c.strokeStyle = P.red
        c.globalAlpha = (1 - ph) * 0.4
        c.beginPath(); c.arc(hp.x, hp.y, 4 + ph * 34 / zoom, 0, TAU); c.stroke()
        c.globalAlpha = 1
        if (u < 0.5) {
          c.globalAlpha = clamp01((0.5 - u) / 0.16)
          c.fillStyle = P.soft
          c.font = '10px "Cascadia Code", Consolas, monospace'
          halo(c, 'JAKARTA · EST. 2015', hp.x, hp.y + 16, P)
          c.fillText('JAKARTA · EST. 2015', hp.x, hp.y + 16)
          c.globalAlpha = 1
        }
      } else if (h === HQ) {
        c.fillStyle = P.red
        c.beginPath(); c.arc(hp.x, hp.y, 3 + 2 * conv, 0, TAU); c.fill()
        if (conv > 0.05) {
          c.strokeStyle = P.red
          for (var ring = 0; ring < 2; ring++) {
            var rp = ((t * 0.8 + ring * 0.5) % 1)
            c.globalAlpha = (1 - rp) * 0.5 * conv
            c.beginPath(); c.arc(hp.x, hp.y, 5 + rp * 26, 0, TAU); c.stroke()
          }
          c.globalAlpha = conv
          c.fillStyle = P.ink
          c.font = '600 11px "Bahnschrift", "Segoe UI", sans-serif'
          halo(c, 'SHA · 全球总部 GLOBAL HQ', hp.x, hp.y - 16, P)
          c.fillText('SHA · 全球总部 GLOBAL HQ', hp.x, hp.y - 16)
          c.globalAlpha = 1
        }
      } else {
        var hTier = HUBS[h][3]
        var size = hTier <= 1 ? 1 : hTier === 2 ? 0.74 : 0.56
        c.fillStyle = lit ? P.ink : P.soft
        c.globalAlpha = lit ? (hTier === 3 ? 0.78 : 0.9) : 0.28
        var popR = popAge < 1 ? 2 + 6 * (1 - popAge) * popAge * 4 : 2
        c.beginPath(); c.arc(hp.x, hp.y, Math.max(0.9, (popAge < 1 ? Math.max(2, popR - 4 * popAge) : 2) * size), 0, TAU); c.fill()
        if (popAge < 1 && hTier <= 1) {
          c.strokeStyle = P.ink
          c.globalAlpha = (1 - popAge) * 0.45
          c.beginPath(); c.arc(hp.x, hp.y, 3 + popAge * 14, 0, TAU); c.stroke()
        }
        c.globalAlpha = 1
      }
    }
    /* 国家级极兔印记：国家首次触达，在国土坐标淡入一枚极简兔标 */
    for (var ci = 0; ci < COUNTRIES.length; ci++) {
      if (prog >= COUNTRY_UNIT[ci] - 0.45) {
        if (!COUNTRY_LIT_AT[ci]) COUNTRY_LIT_AT[ci] = performance.now()
        var cAge = (performance.now() - COUNTRY_LIT_AT[ci]) / 450
        var bq = cam(COUNTRIES[ci][1] * DEG, COUNTRIES[ci][2] * DEG)
        if (bq.z <= 0.05) continue
        drawBunny(c, cx + R * bq.x, cy - R * bq.y,
          Math.max(5.5, R * 0.021), P, ease(clamp01(cAge)) * 0.5)
      }
    }

    /* 货件脉冲沿弧线流动（数量随展开增加） */
    var count = 2 + Math.floor(clamp01(prog / TOTAL_UNITS) * 13)
    for (var pk = 0; pk < count; pk++) {
      var edge = NET[(pk * 7 + Math.floor(t * 3)) % NET.length]
      if (edge[3] === 5) continue
      var from = HUBS[edge[0]]
      var tArc = clamp01(prog - edge[2])
      if (tArc < 0.25) continue
      var pos = ((t * 0.16 * (0.75 + 0.06 * pk)) + pk * 0.37) % 1 * tArc
      var pt = arcPoint(from, HUBS[edge[1]], pos)
      var pp = cam(pt.lat * DEG, pt.lon * DEG)
      if (!dirVisible(pp, pt.r)) continue
      var px = cx + R * pp.x, py = cy - R * pp.y
      c.fillStyle = P.red
      /* 拖尾：沿弧线向后取 4 个采样点，逐渐收细变淡 */
      for (var tr = 1; tr <= 4; tr++) {
        var tp2 = pos - tr * 0.022
        if (tp2 < 0) break
        var tpt = arcPoint(from, HUBS[edge[1]], tp2)
        var tpp = cam(tpt.lat * DEG, tpt.lon * DEG)
        if (!dirVisible(tpp, tpt.r)) continue
        c.globalAlpha = 0.4 * (1 - tr / 5)
        c.beginPath(); c.arc(cx + R * tpp.x, cy - R * tpp.y, 2.2 * (1 - tr * 0.16), 0, TAU); c.fill()
      }
      c.globalAlpha = 0.14
      c.beginPath(); c.arc(px, py, 5.5, 0, TAU); c.fill()
      c.globalAlpha = 0.95
      c.beginPath(); c.arc(px, py, 2.3, 0, TAU); c.fill()
      c.globalAlpha = 1
    }
  }

  /* 经纬网（仅近景可见的淡淡参考线，给球体以「测绘底图」的结构感） */
  function drawGraticule(c, cam, cx, cy, R, P, alpha) {
    c.save()
    c.strokeStyle = P.ink
    c.globalAlpha = alpha
    c.lineWidth = 1
    for (var lat = -60; lat <= 60; lat += 30) {
      c.beginPath()
      var started = false
      for (var lon = -180; lon <= 180; lon += 6) {
        var p = cam(lat * DEG, lon * DEG)
        if (p.z <= 0.02) { started = false; continue }
        var sx = cx + R * p.x, sy = cy - R * p.y
        if (!started) { c.moveTo(sx, sy); started = true } else c.lineTo(sx, sy)
      }
      c.stroke()
    }
    for (var lon2 = -180; lon2 < 180; lon2 += 30) {
      c.beginPath()
      var st2 = false
      for (var la = -90; la <= 90; la += 6) {
        var q = cam(la * DEG, lon2 * DEG)
        if (q.z <= 0.02) { st2 = false; continue }
        var mx = cx + R * q.x, my = cy - R * q.y
        if (!st2) { c.moveTo(mx, my); st2 = true } else c.lineTo(mx, my)
      }
      c.stroke()
    }
    c.restore()
    c.globalAlpha = 1
  }

  /* 简化大陆球体：实底大陆剪影（Stripe 式极简地图）+ 细岸线。
     顶点先变换到镜头坐标，Sutherland–Hodgman 对 z≥0 半空间裁掉背面后填充，
     临边裁剪天然正确；弦长 ≤4° 时临边直线误差为亚像素级。
     保留临边环 / 大气晕 / 体积明暗，dim 背景模式整体压暗。 */
  function drawLandSphere(c, camVec, cx, cy, R, P, dim, reveal, dimMul, shade) {
    reveal = reveal === undefined ? 1 : clamp01(reveal)
    if (reveal <= 0.01) return
    var mul = dimMul === undefined ? 1 : dimMul
    c.save()
    /* 临边环 + 外晕 */
    c.strokeStyle = dim ? P.faint : P.limb
    c.lineWidth = 1
    c.globalAlpha = dim ? 1 : 0.35
    c.beginPath(); c.arc(cx, cy, R, 0, TAU); c.stroke()
    if (!dim) {
      c.globalAlpha = 0.12
      c.beginPath(); c.arc(cx, cy, R * 1.012, 0, TAU); c.stroke()
      /* 大气晕圈：临边外一圈柔和的空气辉光 */
      var halo2 = c.createRadialGradient(cx, cy, R * 0.96, cx, cy, R * 1.12)
      halo2.addColorStop(0, 'rgba(0,0,0,0)')
      halo2.addColorStop(0.45, P.haloEdge)
      halo2.addColorStop(1, 'rgba(0,0,0,0)')
      c.globalAlpha = 1
      c.fillStyle = halo2
      c.fillRect(cx - R * 1.12, cy - R * 1.12, R * 2.24, R * 2.24)
    }
    /* 大陆剪影：逐环填充 + 岸线描边（显影进度按纬度自南向北扫入） */
    var fillA = (dim ? 0.1 : 0.09) * mul
    var lineA = (dim ? 0.2 : 0.3) * mul
    c.fillStyle = P.ink
    c.strokeStyle = P.ink
    c.lineWidth = 1
    for (var r = 0; r < LAND.length; r++) {
      var ring = LAND[r]
      var ramp = clamp01((reveal + 0.06 - ring.latN) / 0.1)
      if (ramp <= 0.002) continue
      var v = ring.v
      var m = v.length / 3
      /* 背面顶点径向吸附到临边圆：填充多边形沿临边自然闭合，消除半空间
         裁剪的「横穿球面直弦」（非洲/美洲临边假边界）；全背面环跳过；
         岸线只描正面相邻段，避免在临边上画出假海岸线。 */
      var fill = []
      var front = []
      var anyFront = false
      for (var i = 0; i < m; i++) {
        var q = camVec(v[i * 3], v[i * 3 + 1], v[i * 3 + 2])
        if (q.z >= 0) {
          fill.push(q.x, q.y)
          front.push(1)
          anyFront = true
        } else {
          var rr2 = Math.sqrt(q.x * q.x + q.y * q.y) || 1e-6
          fill.push(q.x / rr2, q.y / rr2)
          front.push(0)
        }
      }
      if (!anyFront) continue
      var nv = front.length
      c.globalAlpha = fillA * ramp
      c.beginPath()
      c.moveTo(cx + R * fill[0], cy - R * fill[1])
      for (var j = 1; j < nv; j++) {
        c.lineTo(cx + R * fill[j * 2], cy - R * fill[j * 2 + 1])
      }
      c.closePath()
      c.fill()
      c.globalAlpha = lineA * ramp
      c.beginPath()
      for (var j2 = 0; j2 < nv; j2++) {
        var jn = (j2 + 1) % nv
        if (front[j2] || front[jn]) {
          c.moveTo(cx + R * fill[j2 * 2], cy - R * fill[j2 * 2 + 1])
          c.lineTo(cx + R * fill[jn * 2], cy - R * fill[jn * 2 + 1])
        }
      }
      c.stroke()
    }
    /* 球体体积：左上受光、临边压暗（裁剪在球内；dim 过渡期按 shade 淡出） */
    if (!dim || (shade || 0) > 0.02) {
      c.beginPath(); c.arc(cx, cy, R - 0.6, 0, TAU); c.clip()
      var sh = c.createRadialGradient(cx - R * 0.45, cy - R * 0.5, R * 0.08, cx, cy, R * 1.02)
      sh.addColorStop(0, P.volLight)
      sh.addColorStop(0.84, 'rgba(0,0,0,0)')
      sh.addColorStop(1, P.volDark)
      c.globalAlpha = dim ? clamp01(shade) : 1
      c.fillStyle = sh
      c.fillRect(cx - R, cy - R, R * 2, R * 2)
    }
    c.restore()
    c.globalAlpha = 1
  }
  /* 背景/衔接地球：与 ORIGIN 收尾完全同源 —— 同一颗球、同一张 300 线网、
     同一批枢纽点。b ∈ 0..1：ORIGIN 英雄态（上海居中、全亮网络、SHA 标牌）
     → 背景态（26° 相机、网络减半）；sink ∈ 0..1：背景态 → 终幕沉底态。
     LINK/PROFILE 阶段由 b 连续落位，背景不再消失。 */
  function drawGlobeLayer(c, t, P, b, sink) {
    var k = smooth(clamp01(b === undefined ? 1 : b))
    var sk = smooth(clamp01(sink === undefined ? 0 : sink))
    var R = Math.min(viewW, viewH) * lerp(0.36, 0.3, sk)
    var cx = viewW / 2
    var cy = viewH * lerp(lerp(0.56, 0.62, k), 0.88, sk)
    var camLat = lerp(31.2, 26, k)
    var camLon = lerp(121.5 + scene.drag * 0.3, 104 + scene.drag * 60 + t * 2.4, k)
    var cam = makeCam(camLat, camLon)
    var camV = makeVecCam(camLat, camLon)
    drawLandSphere(c, camV, cx, cy, R, P, true, 1, lerp(1, 0.55, sk), 1 - k)
    var netMul = lerp(1, lerp(0.42, 0.3, sk), k)
    for (var e = 0; e < NET.length; e++) {
      var kind = NET[e][3]
      var B = HUBS[NET[e][1]]
      var alpha0 = kind === 3 ? 0.13 : kind === 2 ? 0.3 : kind === 5 ? 0.9
        : (NET[e][0] === HQ ? (B[3] <= 1 ? 0.8 : B[3] === 2 ? 0.5 : 0.32)
                            : (B[3] <= 1 ? 0.55 : B[3] === 2 ? 0.34 : 0.2))
      var width0 = kind === 3 ? 0.6 : kind === 2 ? 0.9 : kind === 5 ? 2.8
        : (NET[e][0] === HQ ? (B[3] <= 1 ? 1.4 : B[3] === 2 ? 1.0 : 0.8)
                            : (B[3] <= 1 ? 1.1 : B[3] === 2 ? 0.9 : 0.7))
      var via = kind === 5 ? HUBS[NET[e][4]] : undefined
      drawArc(c, cam, cx, cy, R, HUBS[NET[e][0]], B, 1, P, alpha0 * netMul, width0, kind !== 5, via, true)
    }
    var dotMul = lerp(1, 0.7, k) * lerp(0.9, 0.5, sk)
    for (var h = 1; h < HUBS.length; h++) {
      if (HUBS[h][3] === 9) continue
      var hp = projHub(HUBS[h], cam, cx, cy, R)
      if (hp.z <= 0) continue
      var hTier = HUBS[h][3]
      c.fillStyle = h === HQ ? P.red : P.ink
      c.globalAlpha = h === HQ ? dotMul : dotMul * (hTier === 3 ? 0.75 : 0.9)
      var rr = h === HQ ? 3 : hTier <= 1 ? 1.9 : hTier === 2 ? 1.4 : 1.05
      c.beginPath(); c.arc(hp.x, hp.y, rr, 0, TAU); c.fill()
    }
    var bMul = lerp(0.55, 0.3, sk)
    for (var gi = 0; gi < COUNTRIES.length; gi++) {
      var gq = cam(COUNTRIES[gi][1] * DEG, COUNTRIES[gi][2] * DEG)
      if (gq.z <= 0.05) continue
      drawBunny(c, cx + R * gq.x, cy - R * gq.y,
        Math.max(4.5, R * 0.02), P, bMul * 0.55)
    }
    if (k < 0.98) {
      var sp = projHub(HUBS[HQ], cam, cx, cy, R)
      if (sp.z > 0) {
        c.globalAlpha = (1 - k) * 0.9
        c.fillStyle = P.ink
        c.font = '600 11px "Bahnschrift", "Segoe UI", sans-serif'
        c.textAlign = 'center'
        c.textBaseline = 'middle'
        halo(c, 'SHA · 全球总部 GLOBAL HQ', sp.x, sp.y - 16, P)
        c.fillText('SHA · 全球总部 GLOBAL HQ', sp.x, sp.y - 16)
      }
    }
    c.globalAlpha = 1
  }

  /* 图纸网格底纹 */
  function drawGrid(c, P) {
    var step = 30
    c.strokeStyle = P.grid
    c.lineWidth = 1
    c.beginPath()
    for (var x = step; x < viewW; x += step) { c.moveTo(x, 0); c.lineTo(x, viewH) }
    for (var y = step; y < viewH; y += step) { c.moveTo(0, y); c.lineTo(viewW, y) }
    c.stroke()
  }

  var revealedRows = 0
  function drawScene() {
    var P = pal()
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0)
    ctx.clearRect(0, 0, viewW, viewH)
    var ph = scene.phase
    var prog = clamp01((performance.now() - scene.phaseStart) / 1000 / scene.duration)
    var t = scene.ambient
    var bgOn = C.background !== false

    if (ph === 0) {
      var r0 = Math.min(viewW, viewH) * 0.17
      drawBadge(ctx, viewW / 2, viewH * 0.55, r0, ease(prog), t, '#ffffff', '#ffffff')
      var lp = (prog - 0.15) / 0.65
      if (lp > 0 && lp < 1) {
        ctx.save()
        ctx.beginPath()
        ctx.rect(viewW / 2 - r0 * 1.15, viewH * 0.55 - r0 * 1.15, r0 * 2.3, r0 * 2.3)
        ctx.clip()
        var ly = viewH * 0.55 - r0 * 1.15 + lp * r0 * 2.3
        ctx.fillStyle = 'rgba(255,255,255,.06)'
        ctx.fillRect(viewW / 2 - r0 * 1.15, ly - 12, r0 * 2.3, 12)
        ctx.fillStyle = 'rgba(255,255,255,.75)'
        ctx.fillRect(viewW / 2 - r0 * 1.15, ly, r0 * 2.3, 1.5)
        ctx.restore()
      }
    } else if (ph === 1) {
      drawOrigin(ctx, prog, t, P)
    } else if (ph === 2) {
      if (bgOn) drawGlobeLayer(ctx, t, P, quintic(clamp01(prog / 0.55)), 0)
      drawGrid(ctx, P)
      drawLink(ctx, viewW / 2, viewH * 0.54, Math.min(viewW * 0.6, 560), prog, t, P)
    } else if (ph === 3) {
      if (bgOn) drawGlobeLayer(ctx, t, P, 1, 0)
      drawGrid(ctx, P)
      var hw = Math.min(viewW * 0.4, 430)
      var hy = viewH * 0.47
      drawHexStrip(ctx, viewW / 2, hy, hw, 66, C.identityId, prog, P, prog > 0.62)
      drawVerify(ctx, viewW / 2, hy, hw, 66, prog, t, P)
      ctx.fillStyle = P.soft
      ctx.font = '10px "Cascadia Code", Consolas, monospace'
      ctx.textAlign = 'center'
      ctx.globalAlpha = clamp01(prog * 2)
      ctx.fillText('BADGE FINGERPRINT · ' + C.identityId, viewW / 2, hy - 58)
      ctx.globalAlpha = 1
    } else if (ph === 4 || ph === 5) {
      drawGrid(ctx, P)
      if (bgOn) drawGlobeLayer(ctx, t, P, 1, 0)
    } else if (ph === 6) {
      drawGrid(ctx, P)
      /* 终幕下沉：~1.4s 内地球连续沉底，随后欢迎区再淡入 */
      if (bgOn) drawGlobeLayer(ctx, t, P, 1, quintic(clamp01(prog / 0.38)))
      drawBadge(ctx, viewW / 2, viewH * 0.22, Math.min(viewW, viewH) * 0.115, ease(Math.min(1, prog * 1.5)), t, P.ink, P.red)
      var dp = (prog - 0.1) / 0.3
      if (dp > 0 && dp < 1) {
        var dx = -viewW * 0.2 + dp * viewW * 1.4
        ctx.fillStyle = P.red
        ctx.globalAlpha = 0.5 * clamp01(1 - Math.abs(dp - 0.5) * 1.2)
        ctx.fillRect(dx, 0, 2, viewH)
        ctx.globalAlpha = 0.08 * clamp01(1 - Math.abs(dp - 0.5) * 1.2)
        ctx.fillRect(dx - 26, 0, 26, viewH)
        ctx.globalAlpha = 1
      }
    }

    if (scene.impulse > 0.01) {
      ctx.strokeStyle = P.red
      ctx.globalAlpha = scene.impulse * 0.4
      ctx.lineWidth = 1.4
      ctx.beginPath()
      ctx.arc(scene.pointer.x * viewW, scene.pointer.y * viewH, (1 - scene.impulse) * 90 + 6, 0, TAU)
      ctx.stroke()
      ctx.globalAlpha = 1
    }

    ui.progress.style.transform = 'scaleX(' + clamp01((phaseIndex + prog) / PHASES.length, 0, 1).toFixed(4) + ')'
  }

  var raf = 0, lastFrame = 0
  function frame(now) {
    raf = 0
    var delta = lastFrame ? Math.max(0, (now - lastFrame) / 1000) : 0
    lastFrame = now
    if (!REDUCED) scene.ambient += delta
    else scene.ambient += Math.min(delta, 0.001)
    scene.impulse = Math.max(0, scene.impulse - delta * 1.6)
    try {
      drawScene()
    } catch (err) {
      if (window.console && console.warn) console.warn('[dsh-jt-startup] draw error:', err)
      raf = 0
      return
    }
    if (!finished) raf = requestAnimationFrame(frame)
  }
  function wake() {
    if (!raf && !finished && !document.hidden) {
      lastFrame = performance.now()
      raf = requestAnimationFrame(frame)
    }
  }
  document.addEventListener('visibilitychange', function () {
    if (document.hidden) { if (raf) cancelAnimationFrame(raf); raf = 0 }
    else wake()
  })
