  /* ── 权限认证 · 终端式授权台（真实清单逐条 granted）────────────────────── */
  var lastScopes = null
  function runInventory() {
    ui.termBody.textContent = ''
    ui.termNow.textContent = '000'
    ui.termTotal.textContent = '---'
    ui.termSummary.textContent = 'resolving ~/.dsh …'
    ui.termGrant.classList.remove('jts-on')
    ui.subZh.textContent = '正在核验本地能力权限…'
    ui.subEn.textContent = 'AUTHORIZING SKILLS / PLUGINS'
    ui.logState.textContent = 'AUTH …'

    var demo = window.__JT_STARTUP_DEMO__
    var fetcher = (C.inventory && !demo)
      ? fetch('/jt-startup/inventory.json', { cache: 'no-store' })
          .then(function (r) { return r.ok ? r.json() : null })
          .catch(function () { return null })
      : Promise.resolve(demo || null)
    var bounded = Promise.race([fetcher, wait(6500).then(function () { return null })])

    return bounded.then(function (data) {
      if (finished) return
      var skills = (data && data.ok && Array.isArray(data.skills)) ? data.skills : null
      var plugins = (data && data.ok && Array.isArray(data.plugins)) ? data.plugins : null
      var offline = !skills && !plugins

      var lines = []
      if (offline) {
        lines.push({
          text: 'offline · ' + (demo ? 'demo scopes · 安装后读取真实清单' : '未读取真实权限清单'),
          kind: 'warn'
        })
        lastScopes = null
        voiceOffline = true
        ui.termSummary.textContent = 'offline preview'
        ui.subZh.textContent = '离线预览 · 权限清单未读取'
        ui.subEn.textContent = 'OFFLINE PREVIEW'
        PHASES[5].note = '离线预览 · 未读取真实权限清单'
        ui.logState.textContent = 'OFFLINE'
      } else {
        var sN = (skills || []).length, pN = (plugins || []).length
        voiceOffline = false
        voiceSkipped = 0
        lastScopes = { skills: sN, plugins: pN, ms: data && data.elapsed_ms }
        var shown = 0
        /* ★ 顺序：先 plugins、后 skills。
           日志区可视高度只有约 6 行（.jts-termBody max-height 172px、行高 23.4px），
           而每追加一行就滚到底部。skills 若排在前面，十几条 plugins 会把它整个顶出
           可视区 —— 看起来就像「只加载了 plugins、没有 skills」。
           把 skills 放在最后，滚到底部时可视区正好同时包含两者。 */
        ;(plugins || []).slice(0, 512).forEach(function (it) {
          /* Loader 清单里被 patch 禁用的条目如实标注为 skipped，不和「已授权」混在一起。 */
          var off = it.enabled === false
          if (off) voiceSkipped++
          lines.push({
            text: (off ? 'skipped  plugin · ' : 'granted  plugin · ')
              + it.name + (it.version ? ' @' + it.version : ''),
            kind: off ? 'dim' : 'ok'
          }); shown++
        })
        ;(skills || []).slice(0, 128).forEach(function (it) {
          lines.push({ text: 'granted  skill · ' + it.name, kind: 'ok' }); shown++
        })
        if (sN + pN - shown > 0) lines.push({ text: '+ ' + (sN + pN - shown) + ' more scopes', kind: 'dim' })
        ui.termTotal.textContent = String(Math.min(sN + pN, 999)).padStart(3, '0')
        ui.termSummary.textContent = 'granted in ' + ((data && data.elapsed_ms) != null ? data.elapsed_ms + ' ms' : '—')
        ui.subZh.textContent = '权限核验完成 · ' + sN + ' skills · ' + pN + ' plugins 已授权'
        ui.subEn.textContent = 'SCOPES GRANTED'
        PHASES[5].note = sN + ' skills · ' + pN + ' plugins · 权限全部就绪'
        if ((data && data.elapsed_ms) != null) PHASES[5].note += ' · ' + data.elapsed_ms + ' ms'
        ui.logState.textContent = 'GRANTED · ' + sN + ' SKILLS · ' + pN + ' PLUGINS'
      }

      /* 大清单自适应：总时长收敛在 ~2.4s（百条级别快速流式滚屏） */
      var step = Math.max(10, Math.min(150, Math.round(3200 / Math.max(1, lines.length))))
      /* 流式追加：行到点才入 DOM，底部跟随滚动 —— 真正的日志滚屏 */
      lines.forEach(function (ln, idx) {
        var row = el('div', 'jts-termLine')
        row.appendChild(el('span', 'jts-termMark jts-m-' + ln.kind, ln.kind === 'ok' ? '✓' : (ln.kind === 'warn' ? '!' : '+')))
        row.appendChild(el('span', 'jts-termText', ln.text))
        setTimeout(function () {
          if (finished) return
          ui.termBody.appendChild(row)
          requestAnimationFrame(function () { row.classList.add('jts-in') })
          ui.termBody.scrollTop = ui.termBody.scrollHeight
          if (ln.kind === 'ok' || ln.kind === 'dim') {
            var now = parseInt(ui.termNow.textContent, 10) || 0
            ui.termNow.textContent = String(Math.min(now + 1, 999)).padStart(3, '0')
            if (idx % 4 === 0) audio.tick()
          }
        }, Math.round(idx * step))
      })
      setTimeout(function () {
        if (finished) return
        ui.termGrant.classList.add('jts-on')
      }, Math.round(Math.min(lines.length * step, 3200) + 150))
      return wait(Math.min(lines.length * step, 3200) + 650)
    })
  }

  /* ── 时间线 ───────────────────────────────────────────────────────────── */
  function run() {
    return Promise.resolve()
      .then(function () { return wait(300) })
      .then(function () { if (finished) return; setPhase(0); return wait(PHASES[0].hold + 400) })
      .then(function () { if (finished) return; setPhase(1); return phaseGate(1) })
      .then(function () { if (finished) return; scene.linked = true; setPhase(2); return phaseGate(2) })
      .then(function () { if (finished) return; setPhase(3); return phaseGate(3) })
      .then(function () { if (finished) return; setPhase(4); return phaseGate(4) })
      .then(function () { if (finished) return; setPhase(5); return phaseGate(5) })
      .then(function () { if (finished) return; setPhase(6); return phaseGate(6) })
      .then(function () { if (finished) return; return wait(260) })
      .then(function () { return finish() })
      .catch(function (err) {
        try { console.warn('[dsh-jt-startup] 动画异常，直接揭幕：', err) } catch (e2) {}
        return finish()
      })
  }

  function phaseGate(i) {
    var p = PHASES[i]
    var extra = p.inventory ? runInventory() : Promise.resolve()
    if (p.action && C.requireInteraction) {
      showAction(p)
      return wait(520)
        .then(waitAction)
        .then(function () { hideAction(); audio.confirm(); return extra })
        .then(function () { return wait(320) })
    }
    return extra.then(function () { return wait(p.hold) })
  }

  function finish() {
    if (finished) return
    finished = true
    releaseAll()
    audio.halt()
    try {
      if (C.mode === 'session') window.sessionStorage.setItem('jt-startup:shown', '1')
      if (C.mode === 'daily') {
        window.localStorage.setItem('jt-startup:day', new Date().toISOString().slice(0, 10))
      }
    } catch (err) { /* 隐私模式下不可写，忽略 */ }
    document.documentElement.classList.remove('jts-lock')
    document.documentElement.style.overflow = ''
    if (document.body) document.body.style.overflow = ''
    root.classList.remove('jts-boot')
    root.classList.add('jts-gone')
    if (raf) cancelAnimationFrame(raf)
    setTimeout(function () {
      if (root && root.parentNode) root.parentNode.removeChild(root)
      try { window.dispatchEvent(new CustomEvent('jt-startup:done')) } catch (err) { /* noop */ }
    }, ms(900))
  }

  function requestSkip() {
    if (skipped || finished) return
    skipped = true
    releaseAll()
    audio.halt()
    finish()
  }

  if (C.allowSkip && ui.skip) {
    ui.skip.hidden = false
    ui.skip.addEventListener('click', function (e) { e.stopPropagation(); requestSkip() })
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') requestSkip()
    })
  } else if (ui.skip) {
    ui.skip.hidden = true
  }

  /* 对外 API：settings 面板里的「立即预览」和重播都走它 */
  window.__JT_STARTUP_API__ = {
    replay: injectSelf,
    skip: requestSkip,
    finish: finish,
    config: C
  }

  document.documentElement.classList.add('jts-lock')
  document.documentElement.style.overflow = 'hidden'
  if (document.body) document.body.style.overflow = 'hidden'
  resize()
  wake()
  /* ★ 运行时已接管：摘掉首屏兜底类 jts-boot。
     两处 9 秒兜底（Host 注入的引导脚本 BOOTSTRAP_JS、本文件开头的保险）都把
     「根节点还带着 jts-boot」当作「splash.js 没能跑起来」的判据。若运行期间不摘，
     整段动画会在第 9 秒被兜底脚本强制移除 —— 而本动画含确认节点要 30 秒左右，
     症状就是「刚播完起于印尼的长镜头，后面几个阶段全没了」。
     .jts-root 自带 position/inset/z-index/background，摘掉后样式不受影响。
     （dsh-startup-screen 的 splash.js 在同样位置做同样的事。） */
  root.classList.remove('jts-boot')

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function () { resize(); run() })
  } else {
    run()
  }
